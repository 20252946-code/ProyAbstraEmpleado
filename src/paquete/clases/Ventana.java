    private void CargarTabla()
    {
        int filas = this.jTable1.getRowCount();
        for (int i = 0; i < filas; i++) 
        {
            modelo.removeRow(0);
        }
        Empleado[] arreglo = GE.getArreglo();
        String[] datos = new String[6];
        for (int i=0; i<GE.getPuntero(); i++)
        {
            if (arreglo[i] instanceof Administrativo) 
            {
                datos[0]="A" ;
            }
            else if (arreglo[i] instanceof Electronico)
            {
                datos[0] = "E";
            }
            else    
            {
                datos[0] = "P";
            }
            datos[1] = arreglo[i].getNom();
            datos[2] = arreglo[i].getDire();
            datos[3] = String.valueOf(arreglo[i].getSueldoB());
            datos[4] = String.valueOf(arreglo[i].getSueldoP());
            datos[5] = String.valueOf(arreglo[i].getBono());
            
            modelo.addRow(datos);
            
        }
        
    }
    
